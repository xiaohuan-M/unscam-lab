import { readFile, writeFile, mkdir, readdir, cp, rm } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url),
  pub = new URL("public/", root);
async function files(dir, prefix = "") {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const name = prefix + entry.name;
    if (entry.isDirectory())
      out.push(...(await files(new URL(entry.name + "/", dir), name + "/")));
    else if (!["sw.js", ".DS_Store"].includes(entry.name)) out.push(name);
  }
  return out.sort();
}
const assets = (await files(pub)).filter(
    (p) =>
      !p.startsWith("downloads/") &&
      (!p.startsWith("reference/") ||
        /^reference\/(docs|book|skill)\//.test(p) ||
        /^reference\/game\/(css|js)\//.test(p)),
  ),
  hash = createHash("sha256");
hash.update(await readFile(new URL(import.meta.url)));
for (const name of assets)
  hash.update(name).update(await readFile(new URL(name, pub)));
const revision = hash.digest("hex").slice(0, 12);
const worker = `// Generated by npm run build. Do not hand-edit.\nconst CACHE='unscam-v3-${revision}';\nconst ASSETS=${JSON.stringify(["./", ...assets.map((p) => "./" + p)])};\nconst URLS=new Set(ASSETS.map(p=>new URL(p,self.registration.scope).href));\nself.addEventListener('install',e=>e.waitUntil(caches.open(CACHE).then(c=>c.addAll(ASSETS))));\nself.addEventListener('activate',e=>e.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('unscam-')&&k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim())));\nself.addEventListener('message',e=>{if(e.data?.type==='SKIP_WAITING')self.skipWaiting();});\nself.addEventListener('fetch',e=>{const u=new URL(e.request.url);u.hash='';u.search='';if(e.request.method!=='GET'||!URLS.has(u.href))return;e.respondWith(fetch(e.request).then(async r=>{if(r.ok)return r;return (await caches.match(u.href))||r;}).catch(async()=> (await caches.match(u.href))||Response.error()));});\n`;
await writeFile(new URL("sw.js", pub), worker);
await rm(new URL("dist/", root), { recursive: true, force: true });
await mkdir(new URL("dist/", root));
await cp(pub, new URL("dist/", root), { recursive: true });
console.log(`Built ${assets.length + 1} files · offline revision ${revision}`);
